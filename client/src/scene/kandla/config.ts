// Конфигурация географической основы Кандлы.
//
// Границы, начало координат и шаг сетки живут в geo/kandla-area.json: этот файл
// читают и скрипты подготовки данных, и сцена. Так «какая область загружена» не
// расходится между пайплайном и рендером.

import area from "../../../geo/kandla-area.json";

export interface GeoBox {
  west: number;
  south: number;
  east: number;
  north: number;
}

export interface KandlaArea {
  name: string;
  title: string;
  subtitle: string;
  /** Код проекции, в которой считаются метры. */
  epsg: number;
  /** Номер зоны UTM (42N → 42). */
  utmZone: number;
  /** Начало локальной системы. Не граница порта и не конкретный причал. */
  origin: { lon: number; lat: number };
  /** Прямоугольник отображения. */
  scene: GeoBox;
  /** Прямоугольник загрузки: шире сцены, чтобы она не обрывалась за причалами. */
  fetch: GeoBox;
  gridMetres: number;
  simplifyMetres: number;
  notes: string[];
}

export const KANDLA_AREA = area as KandlaArea;

/** Папка подготовленных слоёв в public/. */
export const KANDLA_LAYER_BASE = `${import.meta.env.BASE_URL}geo/kandla/`;

/**
 * Высоты поверхности. Условные: измеренных отметок в источнике нет, поэтому
 * суша — плоская плита на 1,6 м выше воды, причальные основания — на 1,75 м.
 * Это не отметки геодезической сети и не глубины.
 */
export const KANDLA_HEIGHTS = {
  /**
   * Верх суши, м над водой. Выше, чем в первой версии (1,6), намеренно: волны в
   * рукаве поднимаются примерно на метр, и низкая плита оказывалась под водой —
   * суша «плавала» в кадре. Запас над гребнем обязателен.
   */
  land: 2.6,
  /** Верх подтверждённого причального основания. */
  quay: 2.75,
  /** Приливные участки (мангры): ниже суши, но выше гребней волн. */
  intertidal: 2.0,
  /** Насколько плита суши уходит под воду — чтобы не было щели у берега. */
  slabDepth: 4.4,
} as const;

