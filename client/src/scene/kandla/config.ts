// Конфигурация географической основы Кандлы.
//
// Границы, начало координат и шаг сетки живут в geo/kandla-area.json: этот файл
// читают и скрипты подготовки данных, и сцена. Так «какая область загружена» не
// расходится между пайплайном и рендером.

import area from "../../../geo/kandla-area.json";

export interface GeoBox {
  west: number;
  south: number;
  east: number;
  north: number;
}

export interface KandlaArea {
  name: string;
  title: string;
  subtitle: string;
  /** Код проекции, в которой считаются метры. */
  epsg: number;
  /** Номер зоны UTM (42N → 42). */
  utmZone: number;
  /** Начало локальной системы. Не граница порта и не конкретный причал. */
  origin: { lon: number; lat: number };
  /** Прямоугольник отображения. */
  scene: GeoBox;
  /** Прямоугольник загрузки: шире сцены, чтобы она не обрывалась за причалами. */
  fetch: GeoBox;
  gridMetres: number;
  simplifyMetres: number;
  notes: string[];
}

export const KANDLA_AREA = area as KandlaArea;

